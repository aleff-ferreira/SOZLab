"""Validate SOZLab on a public-software reference system: TIP3P water + 0.25 M NaCl simulated with OpenMM.

Everything is generated by ``bench/data/make_tip3p_box.py`` (fixed seeds, public force field); the trajectories are not
committed, their SHA-256 sums are in ``meta.json``.  Ground truth always comes from *other* software or from first
principles, never from SOZLab itself:

  V1  zone membership    per frame, SOZLab's occupancy of "water oxygens within r_c of any Na+" equals an independent
                         brute-force minimum-image count (MDAnalysis ``distance_array``) - exact equality expected
  V2  coordination       mean zone occupancy equals 5 x the coordination number integrated from MDAnalysis ``InterRDF``
  V3  survival function  S(tau) equals MDAnalysis ``SurvivalProbability`` (independent implementation, same frames)
  V4  uncertainty        16 chunks of 0.5 ns (4 replicas x 4): empirical spread and 95 % CI coverage of the SE that
                         SOZLab reports from a single chunk
  V5  stride sensitivity residence time vs sampling interval; gap tolerance; experimental dt -> 0 extrapolation
  V6  density map        radial average of the solute-frame density map equals InterRDF for a single ion; far-field bulk
                         density equals N/V
  V7  parallel identity  workers=1 and workers=4 give bitwise-identical tables

    python bench/validate/tip3p_validation.py --data bench/out/tip3p --out docs/evidence/data/tip3p_validation.json
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
import time
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")
REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

import MDAnalysis as mda  # noqa: E402
from MDAnalysis.analysis.rdf import InterRDF  # noqa: E402
from MDAnalysis.lib.distances import distance_array  # noqa: E402

from engine.analysis import SOZAnalysisEngine  # noqa: E402
from engine.models import (  # noqa: E402
    AnalysisOptions,
    DensityMapConfig,
    InputConfig,
    OutputConfig,
    ProbeConfig,
    ProjectConfig,
    SelectionSpec,
    SolventConfig,
    SOZDefinition,
    SOZNode,
)


def project(top, traj, out, cutoff, anchor, *, start=0, stop=None, stride=1, gap_time=None, workers=1, blocks=5,
            sensitivity=True, density=None, parallel_min_seconds=None) -> ProjectConfig:
    return ProjectConfig(
        inputs=InputConfig(topology=str(top), trajectory=str(traj)),
        solvent=SolventConfig(water_resnames=["HOH"], probe=ProbeConfig(selection="name O", position="atom")),
        selections={"anchor": SelectionSpec(label="anchor", selection=anchor)},
        sozs=[SOZDefinition(name="shell", description="validation", root=SOZNode(
            type="distance", params={"selection_label": "anchor", "cutoff": cutoff, "unit": "A"}))],
        analysis=AnalysisOptions(frame_start=start, frame_stop=stop, stride=stride, gap_tolerance_time=gap_time, workers=workers,
                                 uncertainty_blocks=blocks, stride_sensitivity=sensitivity, store_ids=True, store_min_distances=False,
                                 **({} if parallel_min_seconds is None else {"parallel_min_seconds": parallel_min_seconds})),
        outputs=OutputConfig(output_dir=str(out), write_per_frame=True),
        density_maps=list(density or []),
    )


def run(top, traj, out, cutoff, anchor, **kw):
    return SOZAnalysisEngine(project(top, traj, out, cutoff, anchor, **kw)).run()


def first_minimum(r, g, r_lo=2.3, r_hi=4.5):
    """First minimum of g(r) after the first peak (the conventional first-shell radius)."""
    sel = (r >= r_lo) & (r <= r_hi)
    rr, gg = r[sel], np.convolve(g, np.ones(5) / 5, mode="same")[sel]
    peak = int(np.argmax(gg))
    i = peak + int(np.argmin(gg[peak:]))
    return float(rr[i])


def est(summary, key):
    u = summary["uncertainty"].get(key) or {}
    return (float(u.get("value", np.nan)), float(u.get("se", np.nan)), float(u.get("ci95_low", np.nan)),
            float(u.get("ci95_high", np.nan)))


# ----------------------------------------------------------------------------------------------------------------------
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="bench/out/tip3p")
    ap.add_argument("--out", default="docs/evidence/data/tip3p_validation.json")
    ap.add_argument("--quick", action="store_true", help="2 replicas, fewer frames (smoke test)")
    args = ap.parse_args()
    data = Path(args.data)
    meta = json.load(open(data / "meta.json"))
    top = str(data / "system.pdb")
    reps = [str(data / r["file"]) for r in meta["replicas"]]
    if args.quick:
        reps = reps[:2]
    work = Path(tempfile.mkdtemp(prefix="sozlab_tip3p_"))
    out: dict = {"system": {k: meta[k] for k in ("openmm", "platform", "seed", "box_nm", "n_atoms", "n_water", "n_na", "n_cl",
                                                    "temperature_K", "frame_interval_ps", "production_ns_per_replica",
                                                    "water_number_density_A3")},
                 "replica_sha256": {r["file"]: r["sha256"] for r in meta["replicas"]}}
    t_start = time.time()

    # ------------------------------------------------------------------ RDF and first-shell radius (independent code)
    u0 = mda.Universe(top, reps[0])
    na, ow = u0.select_atoms("resname NA"), u0.select_atoms("resname HOH and name O")
    gs, counts = [], []
    for rep in reps:
        u = mda.Universe(top, rep)
        rdf = InterRDF(u.select_atoms("resname NA"), u.select_atoms("resname HOH and name O"), nbins=300, range=(0.0, 9.0))
        rdf.run(step=2)
        gs.append(rdf.results.rdf)
    r = rdf.results.bins
    g = np.mean(gs, axis=0)
    r_c = round(first_minimum(r, g) / 0.05) * 0.05
    box = float(u0.dimensions[0])
    rho = len(ow) / box ** 3
    cn = rho * np.cumsum(4 * np.pi * r ** 2 * g * (r[1] - r[0]))
    cn_rc = float(np.interp(r_c, r, cn))
    out["rdf"] = {"first_peak_A": float(r[np.argmax(g[(r > 2.0)] ) + np.argmax(r > 2.0)]), "r_c_A": r_c, "coordination_number_at_r_c": cn_rc,
                  "expected_zone_occupancy_5_ions": len(na) * cn_rc, "bulk_density_N_over_V": rho}
    print(f"[rdf] first minimum / first-shell radius r_c = {r_c:.2f} A, CN = {cn_rc:.3f}, 5-ion expectation = {len(na) * cn_rc:.2f}", flush=True)

    # ------------------------------------------------------------------ V1 per-frame membership vs brute force
    res0 = run(top, reps[0], work / "v1", r_c, "resname NA")
    z0 = res0.soz_results["shell"]
    n_soz = z0.per_frame["n_solvent"].to_numpy()
    frames = np.linspace(0, len(n_soz) - 1, 300).astype(int)
    mism = 0
    for f in frames:
        u0.trajectory[int(f)]
        d = distance_array(na.positions, ow.positions, box=u0.dimensions)
        n_ref = int((d.min(axis=0) <= r_c).sum())
        mism += int(n_ref != n_soz[int(f)])
    out["V1_membership"] = {"frames_checked": int(len(frames)), "mismatching_frames": mism, "r_c_A": r_c}
    print(f"[V1] membership: {mism} of {len(frames)} sampled frames differ from the brute-force oracle", flush=True)

    # ------------------------------------------------------------------ V2 coordination number
    mean_n = [float(run(top, rep, work / f"v2_{i}", r_c, "resname NA", sensitivity=False).soz_results["shell"].summary["mean_n_solvent"])
              for i, rep in enumerate(reps)]
    out["V2_coordination"] = {"soz_mean_occupancy_per_replica": mean_n, "soz_mean": float(np.mean(mean_n)),
                              "soz_replica_sd": float(np.std(mean_n, ddof=1)) if len(mean_n) > 1 else None,
                              "interrdf_expected": len(na) * cn_rc,
                              "relative_difference": float(np.mean(mean_n) / (len(na) * cn_rc) - 1.0)}
    print(f"[V2] SOZ mean occupancy {np.mean(mean_n):.3f} vs 5 x CN(InterRDF) {len(na) * cn_rc:.3f}", flush=True)

    # ------------------------------------------------------------------ V3 survival function vs independent code
    from waterdynamics import SurvivalProbability as SP

    step, tau_max = 5, 100
    sel = f"name O and around {r_c} resname NA"
    u = mda.Universe(top, reps[0])
    dt = float(u.trajectory.dt) * step
    # (a) the definition, brute force on MDAnalysis updating-selection sets: S(tau) = sum_t |cap_{k<=tau} M(t+k)| / sum_t |M(t)|
    sets = []
    for ts in u.trajectory[::step]:
        sets.append(frozenset(u.select_atoms(sel).indices.tolist()))
    n_f = len(sets)
    num = np.zeros(tau_max + 1)       # sum over origins of |intersection|, per lag
    den = np.zeros(tau_max + 1)       # sum over origins of |M(t)|, per lag (only origins whose window fits)
    macro = np.zeros(tau_max + 1)     # sum of per-origin ratios
    cnt = np.zeros(tau_max + 1)
    for t in range(n_f):
        cur = set(sets[t])
        n0 = len(cur)
        for k in range(min(tau_max, n_f - 1 - t) + 1):
            if k:
                cur &= sets[t + k]
            num[k] += len(cur)
            den[k] += n0
            macro[k] += (len(cur) / n0) if n0 else 0.0
            cnt[k] += 1
    s_pooled = num / den
    s_macro = macro / cnt
    # (b) the published tool (MDAKit waterdynamics, successor of MDAnalysis.analysis.waterdynamics) on the same strided frames
    u2 = mda.Universe(top, reps[0])
    u2.transfer_to_memory(step=step)
    sp = SP(u2, sel)
    sp.run(tau_max=tau_max, step=1, verbose=False)
    t_wd, s_wd = np.asarray(sp.tau_timeseries, int), np.asarray(sp.sp_timeseries, float)
    # (c) SOZLab on exactly the same frames, restricted to origins whose full tau_max window fits (what the references use)
    soz = run(top, reps[0], work / "v3", r_c, "resname NA", stride=step, sensitivity=False)
    surv = soz.soz_results["shell"].survival
    s_soz = surv["S_continuous"].to_numpy(float)[: tau_max + 1]
    # SOZLab pools every origin for which the lag fits; the references use a common origin window. Compare on the common lags.
    d_pool = np.abs(s_soz - s_pooled)
    d_wd = np.abs(s_soz - s_wd[: tau_max + 1])
    out["V3_survival"] = {
        "stride_frames": step, "dt_ps": dt, "tau_max_lags": tau_max,
        "max_abs_diff_vs_bruteforce_pooled": float(d_pool.max()), "max_abs_diff_vs_bruteforce_mean_of_ratios": float(np.abs(s_soz - s_macro).max()),
        "max_abs_diff_vs_waterdynamics": float(d_wd.max()),
        "integral_0_to_tau_max_ps": {"sozlab": float(np.trapz(s_soz, dx=dt)), "bruteforce_pooled": float(np.trapz(s_pooled, dx=dt)),
                                    "waterdynamics": float(np.trapz(s_wd[: tau_max + 1], dx=dt))},
        "note": "SOZLab pools every origin whose lag fits: S(tau) = sum N_tau / sum N_0 (Impey et al. 1983). waterdynamics averages "
                "the per-origin ratios N_tau/N_0; both are exact for their definition, they differ by finite-sample weighting"}
    print(f"[V3] S(tau) vs brute force: {d_pool.max():.2e}; vs waterdynamics: {d_wd.max():.2e} (lags 0..{tau_max} at dt={dt} ps)", flush=True)

    # ------------------------------------------------------------------ V4 uncertainty on chunks
    nfr = len(u0.trajectory)
    q = nfr // 4
    rows = []
    for i, rep in enumerate(reps):
        for c in range(4):
            sm = run(top, rep, work / f"v4_{i}_{c}", r_c, "resname NA", start=c * q, stop=(c + 1) * q, sensitivity=False).soz_results["shell"].summary
            row = {"replica": i, "chunk": c}
            for key in ("mean_n_solvent", "tau_survival_integral", "entry_rate_per_time"):
                v, se, lo, hi = est(sm, key)
                row[key], row[key + "_se"], row[key + "_lo"], row[key + "_hi"] = v, se, lo, hi
            rows.append(row)
    chunks = pd.DataFrame(rows)
    unc = {}
    for key in ("mean_n_solvent", "tau_survival_integral", "entry_rate_per_time"):
        v, se = chunks[key].to_numpy(), chunks[key + "_se"].to_numpy()
        grand = float(np.mean(v))
        cover = float(np.mean((chunks[key + "_lo"].to_numpy() <= grand) & (grand <= chunks[key + "_hi"].to_numpy())))
        unc[key] = {"grand_mean": grand, "empirical_sd_across_chunks": float(np.std(v, ddof=1)), "mean_reported_se": float(np.mean(se)),
                    "ratio_empirical_sd_to_reported_se": float(np.std(v, ddof=1) / np.mean(se)), "coverage_95": cover, "n_chunks": int(len(v))}
        print(f"[V4] {key}: sd/SE = {unc[key]['ratio_empirical_sd_to_reported_se']:.2f}, 95% coverage = {cover:.2f} ({len(v)} chunks)", flush=True)
    out["V4_uncertainty"] = unc
    chunks.to_csv(Path(args.out).with_name("tip3p_chunks.csv"), index=False)

    # ------------------------------------------------------------------ V5 stride sensitivity and gap tolerance
    srows = []
    for stride in (1, 5, 10, 25, 50):
        row = {"stride": stride, "dt_ps": round(stride * meta["frame_interval_ps"], 6)}
        taus, rates, ext, tau_i2, tau_i5 = [], [], [], [], []
        for i, rep in enumerate(reps):
            sm = run(top, rep, work / f"v5_{stride}_{i}", r_c, "resname NA", stride=stride, gap_time=2.0, sensitivity=True).soz_results["shell"].summary
            taus.append(sm["residence"]["continuous"]["tau_survival_integral"])
            tau_i2.append(sm["residence"]["intermittent"]["tau_survival_integral"])
            rates.append(sm["entry_rate_per_time"])
            if sm.get("tau_extrapolation", {}).get("valid"):
                ext.append(sm["tau_extrapolation"]["tau_dt0"])
        row.update(tau_continuous_ps=float(np.mean(taus)), tau_continuous_sd=float(np.std(taus, ddof=1)),
                   tau_intermittent_gap2ps=float(np.mean(tau_i2)), tau_intermittent_gap2ps_sd=float(np.std(tau_i2, ddof=1)),
                   entry_rate_per_ps=float(np.mean(rates)), tau_dt0_internal_extrapolation_ps=float(np.mean(ext)) if ext else None)
        srows.append(row)
    sdf = pd.DataFrame(srows)
    out["V5_stride"] = srows
    print(sdf.to_string(index=False), flush=True)

    # ------------------------------------------------------------------ V6 density map vs InterRDF for one ion
    ion = int(na.indices[0])
    results_v6 = {}
    for spacing in (0.5, 0.25):
        dcfg = DensityMapConfig(name="na_water", species_selection="resname HOH and name O", grid_spacing=spacing, align=True,
                                align_selection=f"index {ion}", region_selection=f"index {ion}", region_padding=9.0,
                                conditioning_policy="permissive", output_format="dx")
        try:
            dres = SOZAnalysisEngine(project(top, reps[0], work / f"v6_{spacing}", r_c, f"index {ion}", density=[dcfg], sensitivity=False)).run()
            d = dres.density_results["na_water"]
            uu = mda.Universe(top, reps[0])
            uu.trajectory[0]
            center = uu.atoms[[ion]].positions[0].astype(float)  # the map lives in the frame-0 coordinates of the solute
            ax = d.axes
            X, Y, Z = np.meshgrid(ax["x"], ax["y"], ax["z"], indexing="ij")
            radius = np.sqrt((X - center[0]) ** 2 + (Y - center[1]) ** 2 + (Z - center[2]) ** 2)
            rho_map = np.asarray(d.grid, float)  # number density of probe atoms, 1/A^3
            gmap = np.asarray(d.g, float)
            rel = np.asarray(d.reliable, bool) if d.reliable is not None else np.ones_like(gmap, bool)
            bins = np.arange(0.0, 8.0 + 1e-9, 0.2)
            idx = np.digitize(radius, bins) - 1
            # Pool every voxel of a shell. Masking voxels first and averaging afterwards would bias g upward (the mask keeps
            # the voxels that fluctuated high), so the masked variant is recorded too, as a documented pitfall.
            g_map = np.array([np.nanmean(gmap[idx == k]) if np.any(idx == k) else np.nan for k in range(len(bins) - 1)])
            g_masked = np.array([np.nanmean(gmap[(idx == k) & rel]) if np.any((idx == k) & rel) else np.nan for k in range(len(bins) - 1)])
            rdf1 = InterRDF(uu.atoms[[ion]], uu.select_atoms("resname HOH and name O"), nbins=len(bins) - 1, range=(0.0, 8.0))
            rdf1.run()
            rb, rg = rdf1.results.bins, rdf1.results.rdf
            far = np.isfinite(g_map) & (rb >= 3.4)
            near = np.isfinite(g_map) & (rb >= 2.0) & (rb < 3.4)
            # coordination number from the map with sub-voxel sampling at the sphere surface vs the same ion's InterRDF
            sub = (np.arange(5) + 0.5) / 5.0 - 0.5
            shell = np.argwhere(np.abs(radius - r_c) < spacing * 1.2)
            inside = (radius <= r_c - spacing * 1.2).astype(float)
            for i, j, k in shell:
                pts = np.array([[X[i, j, k] + a * spacing, Y[i, j, k] + b * spacing, Z[i, j, k] + c * spacing] for a in sub for b in sub for c in sub])
                inside[i, j, k] = float((np.linalg.norm(pts - center, axis=1) <= r_c).mean())
            cn_map = float((rho_map * inside).sum() * spacing ** 3)
            cn_rdf = float(rho * np.sum(4 * np.pi * rb[rb <= r_c] ** 2 * rg[rb <= r_c] * (rb[1] - rb[0])))
            bulk = d.metadata.get("bulk", {}) or {}
            results_v6[str(spacing)] = {
                "grid_spacing_A": spacing, "rms_g_difference_r_ge_3.4A": float(np.sqrt(np.mean((g_map[far] - rg[far]) ** 2))),
                "rms_g_difference_r_ge_3.4A_if_masked_before_averaging": float(np.sqrt(np.nanmean((g_masked[far] - rg[far]) ** 2))),
                "first_peak_g_map": float(np.nanmax(g_map)), "first_peak_g_interrdf": float(rg.max()),
                "coordination_number_map": cn_map, "coordination_number_interrdf": cn_rdf,
                "coordination_relative_difference": cn_map / cn_rdf - 1.0, "reliable_fraction": d.metadata.get("reliable_fraction"),
                "bulk_metadata": {k: v for k, v in bulk.items() if not isinstance(v, (list, dict))}, "bulk_N_over_V": rho,
                "trust": [t for t in dres.qc_summary.get("trust", []) if t["scope"].startswith("density")]}
            print(f"[V6] spacing {spacing}: g(r>=3.4) RMS {results_v6[str(spacing)]['rms_g_difference_r_ge_3.4A']:.3f}; first peak "
                  f"{results_v6[str(spacing)]['first_peak_g_map']:.2f} vs {rg.max():.2f}; CN {cn_map:.3f} vs {cn_rdf:.3f}; bulk {bulk}", flush=True)
        except Exception as exc:  # recorded, not hidden
            import traceback

            results_v6[str(spacing)] = {"error": f"{type(exc).__name__}: {exc}", "trace": traceback.format_exc(limit=4)}
            print(f"[V6] spacing {spacing} failed: {exc}", flush=True)
    out["V6_density"] = results_v6

    # ------------------------------------------------------------------ V7 parallel identity and timing
    t0 = time.time()
    a = run(top, reps[0], work / "v7a", r_c, "resname NA", workers=1, sensitivity=False)
    t_serial = time.time() - t0
    t0 = time.time()
    b = run(top, reps[0], work / "v7b", r_c, "resname NA", workers=4, sensitivity=False, parallel_min_seconds=0.0)
    t_par = time.time() - t0
    pa, pb = a.soz_results["shell"].per_frame, b.soz_results["shell"].per_frame
    same = bool(pa.drop(columns=["anchor"], errors="ignore").equals(pb.drop(columns=["anchor"], errors="ignore")))
    out["V7_parallel"] = {"frames": int(len(pa)), "per_frame_identical": same, "seconds_serial": t_serial, "seconds_workers4": t_par,
                          "workers_used": b.run_info.get("workers_used"), "mode": b.run_info.get("mode")}
    print(f"[V7] serial {t_serial:.1f}s, workers=4 {t_par:.1f}s ({b.run_info.get('mode')}), identical={same}", flush=True)

    out["wall_seconds_total"] = time.time() - t_start
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    json.dump(out, open(args.out, "w"), indent=2, default=float)
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
